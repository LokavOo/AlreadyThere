# 1.4 记忆模式（每个角色可在设置里写 "memory"）：
#   全局：能看到所有角色上一轮的结果与意见原文
#   固定：只看 see 里列出的角色（"self" 表示自己）、最近 rounds 轮
#   全新：每轮都从头开始，只看问题、口径、本轮检索和针对自己的意见（意见中不含他方的数值与出处）
DEFAULT_MEMORY = {
    "生产者": {"mode": "固定", "see": ["self"], "rounds": 1},
    "审查者": {"mode": "全局"},
}


def memory_of(role_settings: dict) -> dict:
    m = dict(DEFAULT_MEMORY.get(role_settings.get("kind"), {"mode": "全新"}))
    m.update(role_settings.get("memory") or {})
    if m.get("mode") not in ("全局", "固定", "全新"):
        raise ValueError(f"memory.mode 只能是 全局/固定/全新，现在是 {m.get('mode')!r}")
    m.setdefault("see", ["self"])
    m.setdefault("rounds", 1)
    return m


def load_secrets(path: str | os.PathLike | None) -> dict:
    secrets = {}
    if path and Path(path).exists():
        for line in Path(path).read_text(encoding="utf-8-sig").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            secrets[k.strip()] = v.strip().strip('"').strip("'")
    # 环境变量优先
    for k in list(secrets) + ["ANTHROPIC_API_KEY", "DEEPSEEK_API_KEY", "DASHSCOPE_API_KEY", "MOONSHOT_API_KEY",
                              "HUNYUAN_API_KEY", "ZHIPU_API_KEY",
                              "ARK_API_KEY", "TAVILY_API_KEY"]:
        if os.environ.get(k):
            secrets[k] = os.environ[k]
    return secrets


def merge_params(s: dict) -> dict:
    """默认参数 + 设置里写的参数（含旧版本的 call_timeout_seconds 兼容）。"""
    params = dict(DEFAULT_PARAMS)
    up = dict(s.get("params", {}))
    if "call_timeout_seconds" in up:  # 2.5：旧设置里的单个超时 → 首包等待和流中断都按它（旧含义）
        up.setdefault("first_packet_timeout_seconds", up["call_timeout_seconds"])
        up.setdefault("stream_idle_timeout_seconds", up["call_timeout_seconds"])
        up.pop("call_timeout_seconds")
    params.update(up)
    s["params"] = params
    return s


def load_settings(path: str | os.PathLike) -> dict:
    return merge_params(json.loads(Path(path).read_text(encoding="utf-8-sig")))
