T2S = {}
for pair in _T2S_PAIRS.split():
    if len(pair) == 2 and pair[0] != pair[1]:
        T2S.setdefault(pair[0], pair[1])


def t2s(s: str) -> str:
    return "".join(T2S.get(c, c) for c in (s or ""))


_IMG = re.compile(r"!\[[^\]]*\]\([^)]*\)")
_LINK = re.compile(r"\[([^\]]*)\]\((?:[^()\s]|\([^)]*\))*(?:\s+\"[^\"]*\")?\)")
_URL = re.compile(r"https?://\S+")
_REF = re.compile(r"\[\d+\]|\[註 ?\d+\]|\[注 ?\d+\]")
_FOOTLINK = re.compile(r"\[\[(?:註|注)? ?[\d a-zA-Z]+\]\]\([^)]*\)")  # 维基的脚注链接 [[4]](#cite_note-4)
_EMPTYLINK = re.compile(r"\[\s*\]\([^)]*\)")


def clean_md(text: str) -> str:
    """把检索接口返回的带排版符号的正文变成可读文本（链接只留文字、去掉图片与网址、表格竖线换成空格）。"""
    if not text:
        return ""
    t = _IMG.sub("", text)
    t = _FOOTLINK.sub("", t)
    for _ in range(2):
        t = _LINK.sub(r"\1", t)
    t = _URL.sub("", t)
    t = _REF.sub("", t)
    t = _EMPTYLINK.sub("", t)
    t = re.sub(r"(\*\*|__|\*|`)", "", t)
    t = re.sub(r"^\s*#{1,6}\s*", "", t, flags=re.M)
    t = re.sub(r"^\s*\|?\s*[-:| ]{3,}\|?\s*$", "", t, flags=re.M)
    t = t.replace("|", " ")
    t = re.sub(r"[ \t 　]+", " ", t)
    t = re.sub(r"\n\s*\n+", "\n", t)
    return t.strip()


_PUNCT = re.compile(r"[\s 　,，。．.、;；:：!！?？'\"“”‘’「」『』《》〈〉()（）\[\]【】{}<>…—\-–~～·・/\\|*#_=+]")


def skeleton(s: str) -> str:
    """比对用的骨架：繁转简、去掉空白与标点。"""
    return _PUNCT.sub("", t2s(s or ""))


def find_skeleton(text: str, quote: str):
    """在 text 里找 quote（按骨架比对）。返回原文中的大致字符区间 (start, end)，找不到返回 None。"""
    q = skeleton(quote)
    if len(q) < 4:
        return None
    # 建立骨架字符到原文位置的映射
    idx, sk = [], []
    for i, ch in enumerate(text or ""):
        c = t2s(ch)
        if not _PUNCT.match(c):
            sk.append(c)
            idx.append(i)
    s = "".join(sk)
    k = s.find(q)
    if k < 0:
        return None
    return idx[k], idx[k + len(q) - 1] + 1
